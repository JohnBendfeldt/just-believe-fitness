export function getWorkoutsForSport(sport: SportMode): WorkoutTemplate[] {
  if (sport === 'running') return RUNNING_WORKOUT_TEMPLATES;
  if (sport === 'rowing') return ROWING_WORKOUT_TEMPLATES;
  return WORKOUT_TEMPLATES;
}

export function isDistanceWorkout(workout: WorkoutTemplate): boolean {
  return typeof workout.targetDistanceMeters === 'number' && workout.targetDistanceMeters > 0;
}

export function getTotalWorkoutDurationSec(workout: WorkoutTemplate): number {
  return workout.segments.reduce((acc, s) => acc + s.durationSec, 0);
}

export function getTotalWorkoutDistanceMeters(workout: WorkoutTemplate): number {
  if (typeof workout.targetDistanceMeters === 'number' && workout.targetDistanceMeters > 0) {
    return workout.targetDistanceMeters;
  }
  return workout.segments.reduce((acc, s) => acc + (s.distanceMeters ?? 0), 0);
}

/**
 * Returns the 0-based active stage index for a distance-driven workout,
 * or `workout.segments.length` once the athlete reaches/exceeds the target distance.
 */
export function getDistanceStageIndex(workout: WorkoutTemplate, distanceMeters: number): number {
  if (!isDistanceWorkout(workout) || workout.segments.length === 0) return 0;
  const totalTarget = getTotalWorkoutDistanceMeters(workout);
  if (distanceMeters >= totalTarget) return workout.segments.length;
  let cursor = 0;
  for (let i = 0; i < workout.segments.length; i++) {
    const segDist = workout.segments[i].distanceMeters ?? 0;
    if (distanceMeters < cursor + segDist) {
      return i;
    }
    cursor += segDist;
  }
  return workout.segments.length;
}

export interface WorkoutOptionGroup {
  label: string;
  workouts: WorkoutTemplate[];
}

/** Groups templates into scannable dropdown sections while preserving order. */
export function groupWorkoutTemplates(
  workouts: WorkoutTemplate[],
  sport: SportMode = 'cycling'
): WorkoutOptionGroup[] {
  const openRide: WorkoutTemplate[] = [];
  const studioTimed: WorkoutTemplate[] = [];
  const enduranceTimed: WorkoutTemplate[] = [];
  const distanceRides: WorkoutTemplate[] = [];

  for (const w of workouts) {
    if (w.isFreeRide || w.category === 'free') {
      openRide.push(w);
    } else if (isDistanceWorkout(w) || w.category === 'distance') {
      distanceRides.push(w);
    } else if (w.category === 'endurance') {
      enduranceTimed.push(w);
    } else {
      studioTimed.push(w);
    }
  }

  const enduranceLabel =
    sport === 'running'
      ? 'Endurance Runs'
      : sport === 'rowing'
        ? 'Endurance Rows'
        : 'Endurance Rides';

  return [
    { label: 'Open Studio', workouts: openRide },
    { label: 'Studio Workouts', workouts: studioTimed },
    { label: enduranceLabel, workouts: enduranceTimed },
    { label: 'Distance Challenges', workouts: distanceRides },
  ].filter((g) => g.workouts.length > 0);
}

/**
 * Formats a workout's selector label without repeating the duration when
 * the workout is free-ride, distance-based, or already includes the time
 * (e.g. "23-Min Signature Burn", "2-Hour Endurance", "50K Challenge", "2,000m Erg Test").
 */
export function formatWorkoutOptionLabel(
  workout: WorkoutTemplate,
  unit: 'min' | 'm' = 'min'
): string {
  if (
    workout.isFreeRide ||
    isDistanceWorkout(workout) ||
    /\b\d+\s*-?\s*(?:min|hr|hour)s?\b/i.test(workout.name)
  ) {
    return workout.name;
  }
  const mins = Math.round(getTotalWorkoutDurationSec(workout) / 60);
  return unit === 'm' ? `${workout.name} (${mins}m)` : `${workout.name} (${mins} min)`;
}

export function getSegmentTargetsForAthlete(
  segment: WorkoutSegment,
  profile: AthleteProfile,
  bikeFamily?: BikeFamilyId | null,
  sport: SportMode = 'cycling'
): {
  minWatts: number;
  maxWatts: number;
  midWatts: number;
  suggestedResistanceLow: number;
  suggestedResistanceHigh: number;
  targetSpeedMphRange?: [number, number];
  targetInclinePct?: number;
  targetSplitSecRange?: [number, number];
} {
  const baseFtp = sport === 'rowing' ? getEffectiveRowFtpWatts(profile) : profile.ftpWatts;
  const minWatts = Math.round(baseFtp * segment.ftpPctRange[0]);
  const maxWatts = Math.round(baseFtp * segment.ftpPctRange[1]);
  const midWatts = Math.round((minWatts + maxWatts) / 2);
  const midCadence = Math.round((segment.cadenceRange[0] + segment.cadenceRange[1]) / 2);

  if (sport === 'running') {
    const thresholdMph = 3600 / getEffectiveRunThresholdPaceSec(profile);
    const pct = segment.pacePctRange ?? segment.ftpPctRange;
    const minMph = Math.max(2.0, Math.round(thresholdMph * pct[0] * 10) / 10);
    const maxMph = Math.max(minMph, Math.round(thresholdMph * pct[1] * 10) / 10);
    return {
      minWatts,
      maxWatts,
      midWatts,
      suggestedResistanceLow: 1,
      suggestedResistanceHigh: 1,
      targetSpeedMphRange: [minMph, maxMph],
      targetInclinePct: segment.inclinePct ?? 1.0,
    };
  }

  if (sport === 'rowing') {
    const slowerSplit = Math.round(rowingWattsToSplitSecPer500m(Math.max(30, minWatts)));
    const fasterSplit = Math.round(rowingWattsToSplitSecPer500m(Math.max(30, maxWatts)));
    return {
      minWatts,
      maxWatts,
      midWatts,
      suggestedResistanceLow: 4,
      suggestedResistanceHigh: 6,
      targetSplitSecRange: [Math.min(fasterSplit, slowerSplit), Math.max(fasterSplit, slowerSplit)],
    };
  }

  const suggestedResistanceLow = suggestBikeResistance(
    minWatts,
    midCadence,
    profile.powerCurve,
    profile.wattGain,
    bikeFamily
  );
  const suggestedResistanceHigh = suggestBikeResistance(
    maxWatts,
    midCadence,
    profile.powerCurve,
    profile.wattGain,
    bikeFamily
  );

  return {
    minWatts,
    maxWatts,
    midWatts,
    suggestedResistanceLow: Math.min(suggestedResistanceLow, suggestedResistanceHigh),
    suggestedResistanceHigh: Math.max(suggestedResistanceLow, suggestedResistanceHigh),
  };
}
